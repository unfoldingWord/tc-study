import { describe, expect, test } from 'bun:test'
import { generateCollectionReadme } from '../lib/services/collectionReadme'

const manifest = {
  name: 'Titus study',
  version: '1.0.0',
  createdAt: '2026-10-28T12:00:00.000Z',
  formatVersion: '1.0.0',
  resources: [{ server: 'git.door43.org', owner: 'unfoldingWord', language: 'en', resourceId: 'ult' }],
  panelLayout: {
    panels: [{ id: 'panel-1', title: 'Scripture', resourceIds: ['ult'], defaultResourceId: 'ult' }],
  },
}

describe('generateCollectionReadme', () => {
  test('names tC Study as the app that made and opens the collection', () => {
    const readme = generateCollectionReadme(manifest, true)
    expect(readme).toContain('**Format:** tC Study collection v1.0.0')
    expect(readme).toContain('1. Open tC Study')
    expect(readme).toContain('Generated by tC Study')
    expect(readme).not.toContain('BT Synergy')
  })

  test('still lists resources and panels, and says whether content is included', () => {
    const withContent = generateCollectionReadme(manifest, true)
    expect(withContent).toContain('- **unfoldingWord/en/ult**')
    expect(withContent).toContain('### Panels (1)')
    expect(withContent).toContain('## Offline Use')
    expect(generateCollectionReadme(manifest, false)).toContain('## Online Required')
  })

  test('accepts the worker manifest, which may lack a panel layout and a format version', () => {
    const readme = generateCollectionReadme(
      { name: 'Bare', version: '1.0.0', resources: [] },
      false
    )
    expect(readme).toContain('### Panels (0)')
    expect(readme).toContain('**Format:** tC Study collection v1.0.0')
  })
})
