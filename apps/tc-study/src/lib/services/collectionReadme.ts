/**
 * README.md written into an exported collection (.zip). Shared by CollectionExportService and the
 * export worker. Prose only: importers read manifest.json, never this file, so the manifest
 * format id ('bt-synergy-collection') is unaffected by the wording here.
 */
import { BRAND_SHORT } from '../../config/brand'

export interface CollectionReadmeInput {
  name: string
  version: string
  description?: string
  createdAt?: string
  formatVersion?: string
  resources: Array<{ server?: string; owner: string; language: string; resourceId: string }>
  panelLayout?: {
    panels: Array<{ id: string; title?: string; resourceIds: string[]; defaultResourceId?: string }>
  }
}

export function generateCollectionReadme(manifest: CollectionReadmeInput, hasContent: boolean): string {
  return `# ${manifest.name}

**Version:** ${manifest.version}
**Created:** ${new Date(manifest.createdAt ?? Date.now()).toLocaleString()}
**Format:** ${BRAND_SHORT} collection v${manifest.formatVersion ?? '1.0.0'}

${manifest.description ? `\n## Description\n\n${manifest.description}\n` : ''}

## Contents

### Resources (${manifest.resources.length})

${manifest.resources.map((r) => `- **${r.owner}/${r.language}/${r.resourceId}**
  - Server: ${r.server}
`).join('\n')}

*Full resource metadata available in \`metadata/\` folder*

### Panels (${manifest.panelLayout?.panels.length ?? 0})

${(manifest.panelLayout?.panels ?? []).map((p) => `- **${p.title || p.id}**
  - Resources: ${p.resourceIds.length}
  - Default: ${p.defaultResourceId || 'None'}
`).join('\n')}

## How to Use

1. Open ${BRAND_SHORT}
2. Go to Collections → Import
3. Select this ZIP file
4. The collection will be imported with all resources and panel configurations

${hasContent ? `
## Offline Use

This collection includes downloaded content in the \`content/\` folder.
You can use these resources offline without internet connection.
` : `
## Online Required

This collection contains only metadata. Resource content will be downloaded on-demand when accessed.
An internet connection is required to load content.
`}

## Package Structure

\`\`\`
manifest.json        - Collection metadata and panel configuration
metadata/            - Full metadata for each resource (title, description, etc.)
content/             - Cached content files (if included)
README.md            - This file
\`\`\`

---

Generated by ${BRAND_SHORT}
`
}
